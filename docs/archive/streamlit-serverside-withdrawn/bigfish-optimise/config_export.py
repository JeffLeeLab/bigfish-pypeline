"""Generate batch-compatible YAML exports for the Streamlit app."""

from __future__ import annotations

import yaml


def _yaml_number(value):
    numeric_value = float(value)
    if numeric_value.is_integer():
        return int(numeric_value)
    return numeric_value


def _normalize_channels(channels):
    normalized = sorted({int(channel) for channel in channels})
    if not normalized:
        raise ValueError("Select at least one channel for YAML export.")
    return normalized


def generate_yaml(
    voxel_size_yx,
    voxel_size_z,
    ex,
    em,
    na,
    ri,
    microscope,
    bg_radius,
    channels,
    auto_threshold,
    manual_thresholds,
    alpha,
    beta,
    subpixel_fitting_mode,
    bf_radius,
    nb_min_spots,
    number_of_workers=2,
    input_pattern="",
    output_dir="",
    output_qc_dir="",
):
    """Build a YAML string matching the current smFISH batch schema."""
    normalized_channels = _normalize_channels(channels)
    normalized_thresholds = {int(channel): _yaml_number(value) for channel, value in manual_thresholds.items()}

    if not auto_threshold and len(normalized_channels) > 2:
        raise ValueError("The current batch schema supports at most two manual-threshold channels.")

    config = {
        "number_of_workers": int(number_of_workers),
        "input_pattern": input_pattern or "/path/to/images/*.tif",
        "output_dir": output_dir or "/path/to/bf_output",
        "output_qc_dir": output_qc_dir or "/path/to/bf_output_qc",
        "voxel_size_yx": _yaml_number(voxel_size_yx),
        "voxel_size_z": _yaml_number(voxel_size_z),
        "ex": _yaml_number(ex),
        "em": _yaml_number(em),
        "NA": _yaml_number(na),
        "RI": _yaml_number(ri),
        "microscope": microscope,
        "bg_radius": int(bg_radius),
        "channels": normalized_channels,
        "auto_threshold": bool(auto_threshold),
        "alpha": _yaml_number(alpha),
        "beta": int(beta),
        "subpixel_fitting_mode": bool(subpixel_fitting_mode),
        "bf_radius": _yaml_number(bf_radius),
        "nb_min_spots": int(nb_min_spots),
    }

    if normalized_channels:
        first_channel = normalized_channels[0]
        config["smFISH_ch1"] = first_channel
        config["smFISH_ch1_thresh"] = normalized_thresholds.get(first_channel, 50)
    if len(normalized_channels) > 1:
        second_channel = normalized_channels[1]
        config["smFISH_ch2"] = second_channel
        config["smFISH_ch2_thresh"] = normalized_thresholds.get(second_channel, 30)

    if not auto_threshold:
        missing_channels = [
            channel for channel in normalized_channels[:2] if channel not in normalized_thresholds
        ]
        if missing_channels:
            missing_list = ", ".join(str(channel) for channel in missing_channels)
            raise ValueError(f"Missing saved manual threshold(s) for channel(s): {missing_list}.")

    header = (
        "# # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #\n"
        "# YAML configuration for Bigfish batch processing\n"
        "# Generated by the bigfish-optimise Streamlit app\n"
        "# # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #\n\n"
    )
    return header + yaml.safe_dump(config, default_flow_style=False, sort_keys=False)